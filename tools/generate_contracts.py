"""Generate TypeScript interfaces and OpenAPI from the actual Pydantic models."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend import schemas
from backend.app import create_app

MODELS = [schemas.Telemetry, schemas.Scenario, schemas.Lineage, schemas.Frame, schemas.Event,
          schemas.SessionState, schemas.Review, schemas.EventDetail, schemas.ReplayCommand,
          schemas.ReviewUpdate, schemas.PreferencesUpdate]


def ts(value):
    if '$ref' in value:
        return value['$ref'].split('/')[-1]
    if 'const' in value:
        return json.dumps(value['const'])
    if 'enum' in value:
        return ' | '.join(json.dumps(x) for x in value['enum'])
    if 'anyOf' in value:
        return ' | '.join(ts(x) for x in value['anyOf'])
    kind = value.get('type')
    if kind == 'array':
        return f'Array<{ts(value["items"])}>'
    if kind == 'object':
        return 'Record<string, unknown>'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind, 'unknown')


def main():
    definitions = {}
    for model in MODELS:
        schema = model.model_json_schema()
        definitions.update(schema.pop('$defs', {}))
        definitions[model.__name__] = schema
    lines = ['// Generated by tools/generate_contracts.py from backend/schemas.py. Do not edit manually.', '']
    for name, schema in definitions.items():
        lines.append(f'export interface {name} {{')
        for field, value in schema.get('properties', {}).items():
            optional = '' if field in schema.get('required', []) else '?'
            lines.append(f'  {field}{optional}: {ts(value)};')
        lines.extend(['}', ''])
    out = ROOT / 'web/src'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'contracts.ts').write_text('\n'.join(lines), encoding='utf-8')
    (ROOT / 'docs/implementation/openapi.json').write_text(json.dumps(create_app().openapi(), indent=2), encoding='utf-8')
    print('Generated TypeScript contracts and OpenAPI from actual server schemas')


if __name__ == '__main__':
    main()
